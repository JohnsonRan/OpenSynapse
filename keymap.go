package main

// Windows virtual-key codes to USB HID keyboard usages, for buttons that
// send a key. Modifiers are bits of the first data byte instead.

var vkToHID = func() map[int]byte {
	m := map[int]byte{
		0x0D: 0x28, 0x1B: 0x29, 0x08: 0x2A, 0x09: 0x2B, 0x20: 0x2C, // Enter Esc Backspace Tab Space
		0xBD: 0x2D, 0xBB: 0x2E, 0xDB: 0x2F, 0xDD: 0x30, 0xDC: 0x31, // - = [ ] \
		0xBA: 0x33, 0xDE: 0x34, 0xC0: 0x35, 0xBC: 0x36, 0xBE: 0x37, 0xBF: 0x38, // ; ' ` , . /
		0x14: 0x39, 0x2C: 0x46, 0x91: 0x47, 0x13: 0x48, // CapsLock PrintScreen ScrollLock Pause
		0x2D: 0x49, 0x24: 0x4A, 0x21: 0x4B, 0x2E: 0x4C, 0x23: 0x4D, 0x22: 0x4E, // Insert Home PgUp Delete End PgDn
		0x27: 0x4F, 0x25: 0x50, 0x28: 0x51, 0x26: 0x52, // Right Left Down Up
		0x90: 0x53, 0x6F: 0x54, 0x6A: 0x55, 0x6D: 0x56, 0x6B: 0x57, 0x6E: 0x63, 0x5D: 0x65, // NumLock Num/*-+. Menu
	}
	for i := range 26 {
		m[0x41+i] = byte(0x04 + i) // A–Z
	}
	for i := range 9 {
		m[0x31+i] = byte(0x1E + i) // 1–9
	}
	m[0x30] = 0x27
	for i := range 12 {
		m[0x70+i] = byte(0x3A + i) // F1–F12
		m[0x7C+i] = byte(0x68 + i) // F13–F24
	}
	for i := range 9 {
		m[0x61+i] = byte(0x59 + i) // Num 1–9
	}
	m[0x60] = 0x62 // Num 0
	return m
}()

var hidToVK = func() map[byte]int {
	m := map[byte]int{}
	for vk, u := range vkToHID {
		m[u] = vk
	}
	return m
}()

// Modifier keys: their bit in the modifier byte (left Ctrl 1 … right Win 128).
var modifierBits = map[int]byte{
	0x11: 1, 0xA2: 1, 0x10: 2, 0xA0: 2, 0x12: 4, 0xA4: 4, 0x5B: 8,
	0xA3: 16, 0xA1: 32, 0xA5: 64, 0x5C: 128,
}
